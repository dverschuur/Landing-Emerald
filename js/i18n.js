export function applyLang(lang) {
    const table = dict[lang] || dict.ES;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const value = table[el.getAttribute('data-i18n')];
        if (value == null) return;
        // Los textos con markup (acentos de color, <br/>, iconos) necesitan innerHTML.
        if (value.includes('<')) el.innerHTML = value;
        else el.textContent = value;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const value = table[el.getAttribute('data-i18n-placeholder')];
        if (value != null) el.placeholder = value;
    });

    document.documentElement.lang = lang === 'EN' ? 'en' : 'es';

    const label = document.getElementById('langToggleLabel');
    if (label) label.textContent = lang === 'EN' ? 'EN' : 'ES';
}
